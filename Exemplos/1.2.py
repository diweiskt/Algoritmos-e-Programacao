# Receba dois valores, calcule e exiba os resultados das
# operações de soma, subtração, divisão e multiplicação entre estes dois números.

x = int(input("Informe primeiro valor: "))

y = int(input("Informe segundo valor: "))

soma = x + y
subtracao = x - y
multiplicacao = x * y
divisao = x / y

print("Resultado da soma: ", soma)
print("Resultado da soma: ", subtracao)
print("Resultado da soma: ", multiplicacao)
print("Resultado da soma: ", divisao)

