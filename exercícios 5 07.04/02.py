'''
Desenvolva um algoritmo que lê 5 números e ao final, exibe a soma destes números.
'''
n1 = int(input('Digite um número: '))
n2 = int(input('Digite outro número: '))
n3 = int(input('Digite outro número: '))
n4 = int(input('Digite outro número: '))
n5 = int(input('Digite outro número: '))
resultado = (n1 + n2 + n3 + n4 + n5)
print(f'A soma de ({n1} + {n2} + {n3} + {n4} + {n5} é: {resultado})')